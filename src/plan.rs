//! Pure target-file / command planning. Port of the text-generation
//! helpers in gozjaro-install's `lib/actions.py` (`_write_fstab`,
//! hostname/hosts, grub sequence, NVRAM entry lookup, kernel pick).

use crate::state::InstallState;
use regex::Regex;

/// /etc/fstab for the installed target. `stamp` is the build/install date
/// (python uses datetime.date.today()).
pub fn fstab(s: &InstallState, stamp: &str) -> String {
    let mut lines = vec![
        format!("# generated by gozjaro-install {stamp}"),
        format!("UUID={}\t/\text4\tnoatime\t0\t1", s.root_uuid),
    ];
    if s.is_uefi {
        lines.push(format!(
            "UUID={}\t/boot/efi\tvfat\tumask=0077\t0\t2",
            s.esp_uuid
        ));
    }
    lines.extend([
        "proc\t/proc\tproc\tdefaults\t0\t0".into(),
        "sysfs\t/sys\tsysfs\tnosuid,noexec,nodev\t0\t0".into(),
        "devpts\t/dev/pts\tdevpts\tgid=5,mode=620\t0\t0".into(),
        "tmpfs\t/run\ttmpfs\tnosuid,nodev\t0\t0".into(),
        "tmpfs\t/dev/shm\ttmpfs\tnosuid,nodev\t0\t0".into(),
    ]);
    lines.push(String::new());
    lines.join("\n")
}

/// /etc/hosts for the target.
pub fn hosts_text(hostname: &str) -> String {
    format!("127.0.0.1\tlocalhost\n127.0.1.1\t{hostname} localhost\n::1\tlocalhost ip6-localhost ip6-node\n")
}

/// The chrooted shell commands for the bootloader, in the exact order the
/// python backend runs them. ORDER MATTERS on UEFI: mkconfig first, THEN
/// install — GRUB's EFI grub-install embeds the generated grub.cfg into the
/// ESP; running it first leaves the ESP image booting with a stale/empty
/// config (the "menu has no Linux entry" symptom).
pub fn grub_commands(s: &InstallState) -> Vec<String> {
    let mkconfig = "grub-mkconfig -o /boot/grub/grub.cfg".to_string();
    if s.is_uefi {
        vec![
            mkconfig,
            "grub-install --target=x86_64-efi --efi-directory=/boot/efi \
             --bootloader-id=Gozjaro --recheck"
                .to_string(),
            "efibootmgr -v || true".to_string(),
        ]
    } else {
        vec![
            mkconfig,
            format!("grub-install --target=i386-pc --recheck {}", s.disk),
        ]
    }
}

/// Find the NVRAM entry that owns the Gozjaro boot loader in
/// `efibootmgr -v` output. The new entry is added as BootNext only, so
/// without a follow-up `efibootmgr -b <entry>` the firmware still boots
/// the live ISO after reboot.
///
/// Note: the "current entry" marker is an asterisk glued directly to the
/// entry name (`Boot0001*`), so the pattern must allow an optional `*`
/// before the whitespace — the python original's regex missed this and
/// would have failed on every real UEFI boot.
pub fn find_gozjaro_boot_entry(efibootmgr_out: &str) -> Option<String> {
    let re = Regex::new(r"(Boot[0-9A-F]+)\*?\s+Gozjaro").ok()?;
    re.captures(efibootmgr_out)?.get(1).map(|m| m.as_str().to_string())
}

/// Pick the newest kernel version dir under /lib/modules. Mirrors the
/// python `vkey`: extract numeric runs, sort by them (non-numeric tails
/// sort last via the string tie-break); take the last.
pub fn latest_kver(versions: &[&str]) -> Option<String> {
    let key = |v: &str| {
        let parts: Vec<u64> = Regex::new(r"\d+").unwrap()
            .find_iter(v)
            .filter_map(|m| m.as_str().parse().ok())
            .collect();
        (parts, v.to_string())
    };
    let mut v: Vec<&str> = versions.to_vec();
    v.sort_by(|a, b| key(a).cmp(&key(b)));
    v.pop().map(String::from)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn state(root_uuid: &str, esp_uuid: &str, is_uefi: bool, disk: &str) -> InstallState {
        let mut s = InstallState::new();
        s.root_uuid = root_uuid.into();
        s.esp_uuid = esp_uuid.into();
        s.is_uefi = is_uefi;
        s.disk = disk.into();
        s
    }

    #[test]
    fn fstab_bios() {
        let s = state("ROOTUUID", "", false, "/dev/sda");
        let fstab = fstab(&s, "2026-10-24");
        assert!(fstab.starts_with("# generated by gozjaro-install 2026-10-24\n"));
        assert!(fstab.contains("UUID=ROOTUUID\t/\text4\tnoatime\t0\t1\n"));
        assert!(!fstab.contains("/boot/efi"));
        assert!(fstab.contains("tmpfs\t/run\ttmpfs\tnosuid,nodev\t0\t0"));
    }

    #[test]
    fn fstab_uefi_has_esp_line() {
        let s = state("ROOTUUID", "ESPUUID", true, "/dev/sda");
        let fstab = fstab(&s, "2026-10-24");
        assert!(fstab.contains("UUID=ESPUUID\t/boot/efi\tvfat\tumask=0077\t0\t2\n"));
    }

    #[test]
    fn grub_order_mkconfig_before_install() {
        let s = state("", "", true, "/dev/sda");
        let cmds = grub_commands(&s);
        assert_eq!(cmds[0], "grub-mkconfig -o /boot/grub/grub.cfg");
        assert!(cmds[1].contains("--target=x86_64-efi"));
        assert!(cmds[1].contains("--bootloader-id=Gozjaro"));
        assert!(cmds[2].starts_with("efibootmgr -v"));

        let bios = state("", "", false, "/dev/sdb");
        let bcmds = grub_commands(&bios);
        assert_eq!(bcmds.len(), 2);
        assert_eq!(bcmds[1], "grub-install --target=i386-pc --recheck /dev/sdb");
    }

    #[test]
    fn nvrAM_entry_lookup() {
        let out = "BootCurrent=0000\n\
                   Timeout=0 seconds\n\
                   Boot0000*  Linuxboot   HD(1,80,60,1a6e9d80,0x6450)\n\
                   Boot0001*  Gozjaro    HD(1,80,60,1a6e9d80,0x6450)\n\
                   Boot0002   UEFI: USB\n";
        assert_eq!(find_gozjaro_boot_entry(out).as_deref(), Some("Boot0001"));
        assert_eq!(find_gozjaro_boot_entry("no entries here"), None);
    }

    #[test]
    fn kernel_pick_sorts_numerically() {
        assert_eq!(
            latest_kver(&["7.1.8", "7.2.0", "7.10.0"]).as_deref(),
            Some("7.10.0")
        );
        assert_eq!(latest_kver(&["7.1.8-gozjaro"]).as_deref(), Some("7.1.8-gozjaro"));
        assert_eq!(latest_kver(&[]), None);
    }

    #[test]
    fn test_hosts_text() {
        assert_eq!(
            hosts_text("mybox"),
            "127.0.0.1\tlocalhost\n127.0.1.1\tmybox localhost\n::1\tlocalhost ip6-localhost ip6-node\n"
        );
    }
}
